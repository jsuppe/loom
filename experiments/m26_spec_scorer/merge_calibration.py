"""
M26 — merge calibration fixtures (one-shot).

Combines:
  * two inline exemplar specs (FIXTURE-high-01, FIXTURE-low-01)
  * tests/data/_agent_band_raw.json (9 high + 9 low from the sub-agent)
  * tests/data/spec_scoring_mid_band_draft.json (21 M25-migration specs)

Writes:
  * tests/data/spec_scoring_calibration.json — the pre-registration lock

Run once, commit the output, then delete this script + the *_raw / *_draft
intermediates. The output JSON is the locked artifact.
"""
from __future__ import annotations

import datetime
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TESTS_DATA = REPO / "tests" / "data"


HIGH_01 = {
    "spec_id": "FIXTURE-high-01",
    "band": "high",
    "parent_req_text": (
        "Loom must expose a local read-only web surface for browsing the "
        "store without CLI knowledge."
    ),
    "description": (
        "`loom ui -p <project>` starts a FastAPI server on localhost:8090 "
        "with Jinja2-rendered HTML views for reqs/findings/specs/files plus "
        "semantic search at /search. JSON API mirrors at /api/reqs, "
        "/api/specs, /api/files. No JS build step; server-side render only. "
        "Single project per server start (no multi-tenant). Opt-in via "
        "pip install loom-cli[ui] (fastapi + uvicorn + jinja2 in extras). "
        "Server binds to 127.0.0.1 only."
    ),
    "acceptance_criteria": [
        "GET http://localhost:8090/ returns 200 with HTML listing project stats",
        "GET /reqs renders a table of all requirements with kind chips and status chips",
        "GET /api/reqs returns JSON shape identical to `loom list --json`",
        "Server refuses to bind 0.0.0.0 (localhost-only enforced)",
        "ImportError surfaced as a friendly message when fastapi extra is missing",
    ],
    "source": "elaborates M23",
}

LOW_01 = {
    "spec_id": "FIXTURE-low-01",
    "band": "low",
    "parent_req_text": "The system should handle errors better.",
    "description": (
        "TBD - will define error handling improvements in next sprint. The "
        "system needs to be more robust and handle various failure modes "
        "gracefully. Implementation details to be determined."
    ),
    "acceptance_criteria": ["TBD"],
    "source": "antipattern: TBD-stuffed",
}


def main() -> None:
    agent = json.loads((TESTS_DATA / "_agent_band_raw.json").read_text(encoding="utf-8"))
    mid = json.loads((TESTS_DATA / "spec_scoring_mid_band_draft.json").read_text(encoding="utf-8"))

    high_band = [HIGH_01] + agent["high"]
    low_band = [LOW_01] + agent["low"]

    assert len(high_band) == 10, f"expected 10 high, got {len(high_band)}"
    assert len(low_band) == 10, f"expected 10 low, got {len(low_band)}"
    assert len(mid) == 21, f"expected 21 mid, got {len(mid)}"

    # ID uniqueness
    ids = [s["spec_id"] for s in high_band + mid + low_band]
    assert len(ids) == len(set(ids)), "duplicate spec_ids found"

    payload = {
        "schema_version": 1,
        "purpose": (
            "M26 spec-quality-scorer pre-registration lock. The grading test "
            "in tests/test_spec_scoring.py loads this fixture set, runs the "
            "produced services.score_specification on each entry, and asserts "
            "the band-ordering + separation thresholds below. Modifying this "
            "file after lock invalidates the experiment."
        ),
        "locked_at": datetime.date.today().isoformat(),
        "spec_under_development": {
            "spec_id": "SPEC-85e02906",
            "parent_req_id": "REQ-6dec889f",
            "rubric_dimensions": [
                "acceptance_criteria",
                "falsifiability",
                "parent_alignment",
                "concreteness",
            ],
            "dimension_max_each": 25,
            "total_max": 100,
        },
        "bands": {
            "high": {
                "description": (
                    "Hand-authored specs elaborating shipped Loom features "
                    "(M11.5/M14/M15/M16/M16.3/M17.1/M20.1/M23/M24/M25). "
                    "Concrete identifiers, falsifiers, >=3 measurable AC each."
                ),
                "expected_median_min": 75,
                "count": len(high_band),
            },
            "mid": {
                "description": (
                    "21 specs generated by the M25 LLM migration (qwen3.5 "
                    "from impl content). Concrete identifiers but ZERO "
                    "acceptance criteria — naturally-occurring thin specs."
                ),
                "expected_median_range": [40, 70],
                "count": len(mid),
            },
            "low": {
                "description": (
                    "Hand-authored antipatterns: TBD-stuffed, pure-restatement, "
                    "vague-aspirational, implementation-only, single-sentence, "
                    "lists-what-not-to-do, process-not-contract, topic-drift, "
                    "hedge-language, cosmetic-stylistic."
                ),
                "expected_median_max": 40,
                "count": len(low_band),
            },
        },
        "ordering_constraint": (
            "median(high) > median(mid) > median(low) MUST hold strictly. "
            "If the ordering is violated, the scorer is not picking up real signal."
        ),
        "separation_thresholds": {
            "high_low_min": 50,
            "high_mid_min": 15,
            "mid_low_min": 15,
        },
        "canary": {
            "high_below_60_max": 0,
            "low_above_60_max": 0,
        },
        "specs": high_band + mid + low_band,
    }

    out_path = TESTS_DATA / "spec_scoring_calibration.json"
    out_text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    out_path.write_text(out_text, encoding="utf-8", newline="\n")

    digest = hashlib.sha256(out_text.encode("utf-8")).hexdigest()
    print(f"wrote {out_path}")
    print(f"  total specs: {len(payload['specs'])} "
          f"(high={len(high_band)} mid={len(mid)} low={len(low_band)})")
    print(f"  sha256:      {digest}")
    print(f"  bytes:       {len(out_text)}")


if __name__ == "__main__":
    main()
